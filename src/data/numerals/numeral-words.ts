export function getUnitForms(n: number, gender: Gender, animacy: Animacy): Forms | undefined {
  const isAnimate = animacy === Animacy.ANIMATE;
  if (n === 1) return isAnimate ? ONE[gender].animate : ONE[gender].inanimate;
  if (n === 2) return isAnimate ? TWO[gender].animate : TWO[gender].inanimate;
  const entry = GENDER_INVARIANT[n];
  return entry ? (isAnimate ? entry.animate : entry.inanimate) : undefined;
}

export function getTensForms(n: number): Forms | undefined {
  return TENS[n];
}

export function getHundredsForms(n: number): Forms | undefined {
  return HUNDREDS[n];
}
