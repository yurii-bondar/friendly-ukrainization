import { Animacy, Case, Gender } from '../../types.js';

type Forms = Record<Case, string>;

function f(nom: string, gen: string, dat: string, acc: string, instr: string, loc: string, voc?: string): Forms {
  return {
    [Case.NOMINATIVE]: nom,
    [Case.GENITIVE]: gen,
    [Case.DATIVE]: dat,
    [Case.ACCUSATIVE]: acc,
    [Case.INSTRUMENTAL]: instr,
    [Case.LOCATIVE]: loc,
    [Case.VOCATIVE]: voc ?? nom,
  };
}

